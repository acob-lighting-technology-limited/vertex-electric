"""Build the Vertex logo SVG variants from logo-trace.json.

Writes to public/brand/:
  vertex-logo.svg            wordmark, ink on light
  vertex-logo-reversed.svg   wordmark, light ink for dark grounds
  vertex-logo-rc.svg         wordmark + "RC: 9872444" registration line
  vertex-logo-rc-reversed.svg
  vertex-mark.svg            the V monogram (favicon / app icon / watermark)
  vertex-mark-mono.svg       single-colour V (currentColor)
and src/ui/brand/logo-paths.ts for the React <Logo> component.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
t = json.loads((ROOT / "scripts/brand/logo-trace.json").read_text())
W, H = 2138, 735
INK, PAPER = "#020202", "#F5F7FA"


def keep(p):
    x0, y0, x1, y1 = p["bbox"]
    return not (x0 <= 1 and y0 <= 1 and x1 >= W - 1 and y1 >= H - 1)


def is_rc(p):  # registration line sits above the wordmark, top-right
    return p["bbox"][3] < 272 and p["bbox"][0] > 1600


ink = [p for p in t["ink"] if keep(p)]
blade = [p for p in t["blade"] if keep(p)]
word_ink = [p for p in ink if not is_rc(p)]
word_blade = [p for p in blade if not is_rc(p)]
rc_ink = [p for p in ink if is_rc(p) and p["bbox"][2] - p["bbox"][0] < 200]  # characters, not the rule
rc_rule = [p for p in blade if is_rc(p)]  # the blue underline


def bbox(paths, pad):
    x0 = min(p["bbox"][0] for p in paths) - pad
    y0 = min(p["bbox"][1] for p in paths) - pad
    x1 = max(p["bbox"][2] for p in paths) + pad
    y1 = max(p["bbox"][3] for p in paths) + pad
    return round(x0), round(y0), round(x1 - x0), round(y1 - y0)


def d(paths):
    return "".join(p["d"] for p in paths)


GRAD = """<linearGradient id="vx-blade" x1="1" y1="0" x2="0" y2="1">
<stop offset="0" stop-color="#0078FE"/><stop offset=".55" stop-color="#0050FD"/><stop offset="1" stop-color="#00249E"/>
</linearGradient>"""


def svg(vb, body, title):
    x, y, w, h = vb
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{x} {y} {w} {h}" role="img" aria-label="{title}">'
        f"<title>{title}</title><defs>{GRAD}</defs>{body}</svg>\n"
    )


def word(ink_color, with_rc):
    body = f'<path fill="{ink_color}" d="{d(word_ink)}"/><path fill="url(#vx-blade)" d="{d(word_blade)}"/>'
    if with_rc:
        body += f'<path fill="{ink_color}" d="{d(rc_ink)}"/><path fill="url(#vx-blade)" d="{d(rc_rule)}"/>'
    return body


out = ROOT / "public/brand"
out.mkdir(parents=True, exist_ok=True)
vb_word = bbox(word_ink, 8)
vb_rc = bbox(ink, 8)
(out / "vertex-logo.svg").write_text(svg(vb_word, word(INK, False), "Vertex"))
(out / "vertex-logo-reversed.svg").write_text(svg(vb_word, word(PAPER, False), "Vertex"))
(out / "vertex-logo-rc.svg").write_text(svg(vb_rc, word(INK, True), "Vertex, RC 9872444"))
(out / "vertex-logo-rc-reversed.svg").write_text(svg(vb_rc, word(PAPER, True), "Vertex, RC 9872444"))

# Monogram: the V glyph and its blade, centred in a square.
v_ink = [p for p in word_ink if p["bbox"][2] < 600]
v_blade = [p for p in word_blade if p["bbox"][2] < 600]
x, y, w, h = bbox(v_ink, 0)
side = max(w, h) + 60
sq = (round(x + w / 2 - side / 2), round(y + h / 2 - side / 2), side, side)
(out / "vertex-mark.svg").write_text(
    svg(sq, f'<path fill="{INK}" d="{d(v_ink)}"/><path fill="url(#vx-blade)" d="{d(v_blade)}"/>', "Vertex")
)
(out / "vertex-mark-mono.svg").write_text(
    svg(sq, f'<path fill="currentColor" d="{d(v_ink)}"/>', "Vertex")
)

ts = f"""// Generated by scripts/brand/build-logo.py from the traced client logo. Do not edit by hand.
export const wordmarkViewBox = "{' '.join(map(str, vb_word))}";
export const registrationViewBox = "{' '.join(map(str, vb_rc))}";
export const markViewBox = "{' '.join(map(str, sq))}";
export const wordInk = "{d(word_ink)}";
export const wordBlade = "{d(word_blade)}";
export const rcInk = "{d(rc_ink)}";
export const rcRule = "{d(rc_rule)}";
export const markInk = "{d(v_ink)}";
export const markBlade = "{d(v_blade)}";
"""
(ROOT / "src/ui/brand").mkdir(parents=True, exist_ok=True)
(ROOT / "src/ui/brand/logo-paths.ts").write_text(ts)
print("viewboxes", vb_word, vb_rc, sq)
